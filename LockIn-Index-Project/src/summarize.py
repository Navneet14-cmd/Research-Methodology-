"""Summary tables behind each table/figure of the paper, plus the data file for the demo.

Usage: python3 src/summarize.py results demo
Reads results/results.json, results/extra.json, results/rules.json, results/tables/*.csv
Writes results/tables/{category_summary,provider_summary,architecture_groups,
       sensitivity_trials,egress_exit_cost}.csv and demo/data.js
"""
import csv, json, os, sys

RES, DEMO = sys.argv[1], sys.argv[2]
TD = os.path.join(RES, "tables")
R = json.load(open(os.path.join(RES, "results.json")))
EX = json.load(open(os.path.join(RES, "extra.json")))
RULES = json.load(open(os.path.join(RES, "rules.json")))

def write(name, header, rows):
    with open(os.path.join(TD, name), "w", newline="") as f:
        w = csv.writer(f); w.writerow(header); w.writerows(rows)

write("category_summary.csv",  # Fig. 3 (RQ2)
      ["category", "resources", "share_of_resources_pct", "share_of_lockin_mass_pct", "configs_containing_pct", "resource_lii"],
      [[k, v["resources"], round(100 * v["share_res"], 2), round(100 * v["share_mass"], 2), round(100 * v["prevalence"], 2), round(v["lii"], 1)]
       for k, v in sorted(R["rq2"].items(), key=lambda kv: -kv[1]["share_mass"])])
write("provider_summary.csv",  # Table II / Fig. 2 (RQ1)
      ["provider", "configs", "mean", "median", "sd", "q1", "q3", "min", "max"],
      [[p, v["n"]] + [round(v[k], 2) for k in ("mean", "median", "sd", "q1", "q3", "min", "max")] for p, v in R["rq1"].items()])
t = R["rq3"]["test"]
write("architecture_groups.csv",  # Table III / Fig. 4 (RQ3)
      ["group", "configs", "median", "mean"],
      [[g, v["n"], round(v["median"], 2), round(v["mean"], 2)] for g, v in R["rq3"].items() if g != "test"]
      + [[], ["Mann-Whitney (K8s vs PaaS)", f"U={t['U']}", f"z={t['z']:.2f}", f"p={t['p']:.2e}"], ["Cliff's delta", round(t["cliffs_delta"], 3)]])
write("sensitivity_trials.csv",  # Fig. 5 (RQ4)
      ["trial_sorted", "spearman_config_ranking", "spearman_category_ranking"],
      [[i, round(a, 4), round(b, 4)] for i, (a, b) in enumerate(zip(R["rhos"], R["cat_rhos"]), 1)])
write("egress_exit_cost.csv",  # Fig. 6
      ["volume_GB", "AWS_usd", "Azure_usd", "GCP_usd"],
      [[v, EX[f"egress_{v}"]["AWS"], EX[f"egress_{v}"]["Azure"], EX[f"egress_{v}"]["GCP"]] for v in (1000, 10000, 100000, 1000000)])

# ---- demo data: every configuration with its resources
res_by_cfg = {}
for r in csv.DictReader(open(os.path.join(TD, "resources.csv"))):
    res_by_cfg.setdefault(r["config_id"], []).append([r["resource_type"], r["category"], float(r["resource_lii"])])
configs = []
for r in csv.DictReader(open(os.path.join(TD, "configurations.csv"))):
    configs.append(dict(id=r["config_id"], repo=r["repository"], path=r["path"], provider=r["provider"],
                        group=r["architecture_group"], lii=float(r["lii"]), resources=res_by_cfg[r["config_id"]]))
repo_info = {}
REPOS = sys.argv[3] if len(sys.argv) > 3 else "data/repositories.csv"
if os.path.exists(REPOS):
    for r in csv.DictReader(open(REPOS)):
        repo_info[r["repository"]] = dict(sha=r["commit_sha"], license=r["license"], n=int(r["configs_included"]), status=r["status"])
demo = dict(rules=RULES, repos=repo_info, configs=configs, summary=R["summary"], rq1=R["rq1"], rq2=R["rq2"], rq3=R["rq3"],
            rq4=dict(R["rq4"], rhos=R["rhos"], cat_rhos=R["cat_rhos"]), extra=EX)
os.makedirs(DEMO, exist_ok=True)
with open(os.path.join(DEMO, "data.js"), "w") as f:
    f.write("// Generated by src/summarize.py from the analysis results. Do not edit by hand.\n")
    f.write("window.LII_DATA = " + json.dumps(demo, separators=(",", ":"), default=dict) + ";\n")
print("summary tables and demo/data.js written")
